export interface ChatTurn {
  role: "user" | "assistant";
  content: string;
}

export interface GenerateInput {
  system: string;
  messages: ChatTurn[];
  signal?: AbortSignal;
  maxTokens?: number;
}

/**
 * Provider abstraction. All implementations run server-side only; API keys never reach
 * the browser. Add new providers (e.g. a UAE-hosted model) by implementing this interface.
 */
export interface ChatProvider {
  /** Stable id stored with messages: "anthropic" | "demo" */
  readonly id: string;
  /** Human-readable label shown in the UI */
  readonly label: string;
  /** Whether output is generated by a real language model. */
  readonly isGenerative: boolean;
  stream(input: GenerateInput): AsyncIterable<string>;
  complete(input: GenerateInput): Promise<string>;
}

export class ProviderError extends Error {
  constructor(
    readonly code: "TIMEOUT" | "UNAVAILABLE" | "REFUSAL" | "RATE_LIMITED" | "CONFIG" | "UNKNOWN",
    message: string,
  ) {
    super(message);
    this.name = "ProviderError";
  }
}
